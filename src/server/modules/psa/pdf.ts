import "server-only";
import { PDFDocument, StandardFonts, rgb, type PDFFont } from "pdf-lib";
import type { InvoiceDetail } from "./service";
import { INVOICE_STATUS_LABEL } from "./rules";

const A4 = { w: 595.28, h: 841.89 };
const M = 56;

const money = (paise: number | bigint, currency: string) => {
  const n = Number(paise) / 100;
  const s = new Intl.NumberFormat("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(n);
  return `${currency === "INR" ? "Rs." : currency} ${s}`;
};
const clean = (s: string) => s.replace(/₹/g, "Rs.").replace(/[^\x20-\x7e]/g, "?");
const addr = (a: Record<string, string>) => [a.line1, a.line2, [a.city, a.state, a.pincode].filter(Boolean).join(" "), a.email].filter(Boolean).map(clean);
const fmtDate = (d: string | null) => (d ? new Date(d + "T00:00:00Z").toLocaleDateString("en-IN", { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" }) : "—");

/** A4 tax invoice: seller and buyer blocks, line table, GST and totals, notes. */
export async function renderInvoicePdf(inv: InvoiceDetail): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(`Invoice ${inv.number}`); doc.setAuthor(inv.company); doc.setCreator("erp"); doc.setProducer("erp");
  const r = await doc.embedFont(StandardFonts.Helvetica), b = await doc.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(0.11, 0.12, 0.14), muted = rgb(0.42, 0.44, 0.48), rule = rgb(0.85, 0.86, 0.88);
  let page = doc.addPage([A4.w, A4.h]);
  let y = A4.h - M;
  const text = (s: string, x: number, size: number, font: PDFFont = r, color = ink) => page.drawText(clean(s), { x, y, size, font, color });
  const right = (s: string, xRight: number, size: number, font: PDFFont = r, color = ink) => page.drawText(clean(s), { x: xRight - font.widthOfTextAtSize(clean(s), size), y, size, font, color });
  const line = () => page.drawLine({ start: { x: M, y }, end: { x: A4.w - M, y }, thickness: 0.6, color: rule });

  text(inv.company, M, 18, b); right("TAX INVOICE", A4.w - M, 14, b, muted); y -= 16;
  for (const l of addr(inv.company_address)) { text(l, M, 9.5, r, muted); y -= 12; }
  if (inv.company_gstin) { text(`GSTIN ${inv.company_gstin}`, M, 9.5, r, muted); y -= 12; }
  y -= 10; line(); y -= 22;

  const colX = A4.w / 2 + 10;
  text("Billed to", M, 9, b, muted); text("Invoice", colX, 9, b, muted); y -= 14;
  text(inv.client, M, 11.5, b); text(`${inv.number}`, colX, 11.5, b); y -= 14;
  const left = [...addr(inv.client_address), ...(inv.client_gstin ? [`GSTIN ${inv.client_gstin}`] : [])];
  const rightCol = [`Issued ${fmtDate(inv.issued_on)}`, `Due ${fmtDate(inv.due_on)}`, `Period ${fmtDate(inv.period_from)} – ${fmtDate(inv.period_to)}`, ...(inv.project ? [`Project ${inv.project}`] : []), `Status ${INVOICE_STATUS_LABEL[inv.status]}`];
  for (let i = 0; i < Math.max(left.length, rightCol.length); i++) {
    if (left[i]) text(left[i], M, 9.5);
    if (rightCol[i]) text(rightCol[i], colX, 9.5);
    y -= 12;
  }
  y -= 18;

  const cols = { desc: M, qty: 360, rate: 440, amt: A4.w - M };
  text("Description", cols.desc, 9, b, muted); right("Qty", cols.qty, 9, b, muted); right("Rate", cols.rate, 9, b, muted); right("Amount", cols.amt, 9, b, muted); y -= 8; line(); y -= 16;
  for (const l of inv.lines) {
    if (y < 140) { page = doc.addPage([A4.w, A4.h]); y = A4.h - M; }
    let desc = clean(l.description);
    while (r.widthOfTextAtSize(desc, 10) > cols.qty - M - 50 && desc.length > 4) desc = desc.slice(0, -4) + "…";
    text(desc, cols.desc, 10); right(String(l.quantity), cols.qty, 10); right(money(l.unit_paise, inv.currency), cols.rate, 10); right(money(l.amount_paise, inv.currency), cols.amt, 10); y -= 16;
  }
  y -= 4; line(); y -= 18;
  right("Subtotal", cols.rate, 10, r, muted); right(money(inv.subtotal_paise, inv.currency), cols.amt, 10); y -= 16;
  right(`GST ${(inv.tax_rate_bp / 100).toFixed(inv.tax_rate_bp % 100 ? 2 : 0)}%`, cols.rate, 10, r, muted); right(money(inv.tax_paise, inv.currency), cols.amt, 10); y -= 18;
  right("Total due", cols.rate, 12, b); right(money(Number(inv.subtotal_paise) + Number(inv.tax_paise), inv.currency), cols.amt, 12, b); y -= 30;

  if (inv.notes) {
    text("Notes", M, 9, b, muted); y -= 13;
    for (const l of inv.notes.split(/\r?\n/).slice(0, 8)) { text(l.slice(0, 110), M, 9.5); y -= 12; }
  }
  page.drawText(clean(`${inv.company} · ${inv.number} · generated by erp`), { x: M, y: 36, size: 8, font: r, color: muted });
  return doc.save();
}
